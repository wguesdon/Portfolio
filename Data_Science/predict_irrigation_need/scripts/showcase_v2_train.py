def parse_args():
    """Parse command line arguments."""
    parser = argparse.ArgumentParser(description="Showcase v2: 4-model training")
    parser.add_argument("--test", action="store_true",
                        help="Fast test mode: 10%% subsample, 3 folds, 500 estimators")
    parser.add_argument("--skip-realmlp", action="store_true",
                        help="Skip RealMLP training (requires pytabkit + GPU)")
    parser.add_argument("--models", default="xgb,lgb,cat,realmlp",
                        help="Comma-separated model list (default: xgb,lgb,cat,realmlp)")
    args, _ = parser.parse_known_args()
    return args


def run():
    """Main training entry point."""
    args = parse_args()

    # Detect SageMaker or local paths
    sm_training = os.environ.get("SM_CHANNEL_TRAINING")
    sm_model_dir = os.environ.get("SM_MODEL_DIR")

    if sm_training:
        data_dir = Path(sm_training)
        output_dir = Path(sm_model_dir or "/opt/ml/model")
        sub_dir = output_dir
    else:
        script_dir = Path(__file__).resolve().parent.parent
        data_dir = script_dir / "data" / "raw"
        output_dir = script_dir / "predictions"
        sub_dir = script_dir / "submissions"

    output_dir.mkdir(parents=True, exist_ok=True)
    sub_dir.mkdir(parents=True, exist_ok=True)

    # Config
    test_mode = args.test
    n_folds = 3 if test_mode else 5
    n_estimators = 500 if test_mode else 15000
    early_stop = 50 if test_mode else 500
    models_to_train = [m.strip() for m in args.models.split(",")]

    if test_mode:
        print("=" * 50)
        print("  TEST MODE: subsampled data, fast training")
        print("=" * 50)

    # Load data
    print("Loading data...")
    train = pd.read_csv(data_dir / "train.csv")
    test = pd.read_csv(data_dir / "test.csv")
    orig = pd.read_csv(data_dir / "irrigation_prediction.csv")
    test_ids = test["id"]
    print(f"  Train: {train.shape}, Test: {test.shape}, Original: {orig.shape}")

    # Encode target
    le = LabelEncoder()
    le.fit(LABEL_ORDER)
    y = le.transform(train[TARGET])
    y_orig = le.transform(orig[TARGET])

    # Subsample in test mode
    if test_mode:
        from sklearn.model_selection import train_test_split
        train, _ = train_test_split(
            train, train_size=0.1, stratify=y, random_state=SEED,
        )
        y = le.transform(train[TARGET])
        test = test.sample(frac=0.1, random_state=SEED).reset_index(drop=True)
        test_ids = test["id"]
        train = train.reset_index(drop=True)
        print(f"  [TEST] Subsampled: Train={train.shape}, Test={test.shape}")

    # Feature engineering
    train, test, orig, feature_cols, interaction_cols = build_all_static_features(
        train, test, orig,
    )

    X = train
    X_test = test
    X_orig = orig

    # Train models
    results = {}

    if "xgb" in models_to_train:
        def xgb_fn(X_tr, y_tr, X_va, y_va):
            return train_xgb_fold(X_tr, y_tr, X_va, y_va, n_estimators, early_stop)

        oof, pred, cv = run_model_cv(
            "xgb", xgb_fn, X, y, X_test, X_orig, y_orig,
            feature_cols, interaction_cols, n_folds, n_estimators, early_stop,
            output_dir, sub_dir, test_ids, le,
        )
        results["xgb"] = cv

    if "lgb" in models_to_train:
        def lgb_fn(X_tr, y_tr, X_va, y_va):
            return train_lgb_fold(X_tr, y_tr, X_va, y_va, n_estimators, early_stop)

        oof, pred, cv = run_model_cv(
            "lgb", lgb_fn, X, y, X_test, X_orig, y_orig,
            feature_cols, interaction_cols, n_folds, n_estimators, early_stop,
            output_dir, sub_dir, test_ids, le,
        )
        results["lgb"] = cv

    if "cat" in models_to_train:
        def cat_fn(X_tr, y_tr, X_va, y_va):
            return train_cat_fold(X_tr, y_tr, X_va, y_va, n_estimators, early_stop)

        oof, pred, cv = run_model_cv(
            "cat", cat_fn, X, y, X_test, X_orig, y_orig,
            feature_cols, interaction_cols, n_folds, n_estimators, early_stop,
            output_dir, sub_dir, test_ids, le,
        )
        results["cat"] = cv

    if "realmlp" in models_to_train and not args.skip_realmlp:
        try:
            from pytabkit.models.sklearn.sklearn_interfaces import RealMLP_TD_Classifier  # noqa: F401

            oof, pred, cv = run_model_cv(
                "realmlp", train_realmlp_fold, X, y, X_test, X_orig, y_orig,
                feature_cols, interaction_cols, n_folds, n_estimators, early_stop,
                output_dir, sub_dir, test_ids, le,
            )
            results["realmlp"] = cv
        except ImportError:
            print("WARNING: pytabkit not installed, skipping RealMLP")

    # Summary
    print(f"\n{'=' * 50}")
    print("  TRAINING COMPLETE")
    print(f"{'=' * 50}")
    for name, cv in results.items():
        print(f"  {name:10s}  CV = {cv:.5f}")
    print(f"\n  Predictions saved to: {output_dir}")
    print(f"  Submissions saved to: {sub_dir}")


if __name__ == "__main__":
    run()
