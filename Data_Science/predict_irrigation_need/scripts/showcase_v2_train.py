def train_xgb_fold(X_tr, y_tr, X_va, y_va, n_estimators, early_stop):
    """Train XGBoost on one fold with balanced weights.

    Args:
        X_tr: Training features.
        y_tr: Training target.
        X_va: Validation features.
        y_va: Validation target.
        n_estimators: Max boosting rounds.
        early_stop: Early stopping patience.

    Returns:
        Fitted XGBClassifier.
    """
    from xgboost import XGBClassifier

    has_gpu = __import__("shutil").which("nvidia-smi") is not None
    model = XGBClassifier(
        objective="multi:softprob",
        num_class=3,
        eval_metric="mlogloss",
        max_depth=6,
        learning_rate=0.01,
        n_estimators=n_estimators,
        subsample=0.8,
        colsample_bytree=0.8,
        max_bin=1024,
        tree_method="hist",
        device="cuda" if has_gpu else "cpu",
        random_state=SEED,
        n_jobs=-1,
        verbosity=0,
    )
    weights = compute_sample_weight("balanced", y_tr)
    model.fit(
        X_tr, y_tr,
        eval_set=[(X_va, y_va)],
        sample_weight=weights,
        verbose=False,
    )
    return model


def train_lgb_fold(X_tr, y_tr, X_va, y_va, n_estimators, early_stop):
    """Train LightGBM on one fold with is_unbalance.

    Args:
        X_tr: Training features.
        y_tr: Training target.
        X_va: Validation features.
        y_va: Validation target.
        n_estimators: Max boosting rounds.
        early_stop: Early stopping patience.

    Returns:
        Fitted LGBMClassifier.
    """
    import lightgbm as lgb

    model = lgb.LGBMClassifier(
        objective="multiclass",
        num_class=3,
        num_leaves=77,
        learning_rate=0.01,
        n_estimators=n_estimators,
        subsample=0.8,
        colsample_bytree=0.7,
        reg_lambda=7.0,
        is_unbalance=True,
        random_state=SEED,
        n_jobs=-1,
        verbosity=-1,
    )
    model.fit(
        X_tr, y_tr,
        eval_set=[(X_va, y_va)],
        callbacks=[
            lgb.early_stopping(early_stop, verbose=False),
            lgb.log_evaluation(0),
        ],
    )
    return model


def train_cat_fold(X_tr, y_tr, X_va, y_va, n_estimators, early_stop):
    """Train CatBoost on one fold with balanced weights.

    Args:
        X_tr: Training features.
        y_tr: Training target.
        X_va: Validation features.
        y_va: Validation target.
        n_estimators: Max boosting rounds.
        early_stop: Early stopping patience.

    Returns:
        Fitted CatBoostClassifier.
    """
    from catboost import CatBoostClassifier

    has_gpu = __import__("shutil").which("nvidia-smi") is not None
    model = CatBoostClassifier(
        loss_function="MultiClass",
        classes_count=3,
        auto_class_weights="Balanced",
        depth=6,
        learning_rate=0.04,
        iterations=n_estimators,
        l2_leaf_reg=0.5,
        random_strength=8.0,
        bagging_temperature=0.4,
        task_type="GPU" if has_gpu else "CPU",
        random_seed=SEED,
        verbose=0,
    )
    model.fit(X_tr, y_tr, eval_set=(X_va, y_va), early_stopping_rounds=early_stop)
    return model


def train_realmlp_fold(X_tr, y_tr, X_va, y_va):
    """Train RealMLP on one fold using pytabkit.

    Uses Mahog's RealMLP approach with internal ensembling (n_ens=5).

    Args:
        X_tr: Training features (numpy or DataFrame).
        y_tr: Training target.
        X_va: Validation features.
        y_va: Validation target.

    Returns:
        Fitted RealMLP_TD_Classifier.
    """
    from pytabkit.models.sklearn.sklearn_interfaces import RealMLP_TD_Classifier

    model = RealMLP_TD_Classifier(
        n_cv=1,
        n_refit=0,
        n_ens=5,
        device="cuda",
        verbosity=0,
    )
    model.fit(X_tr.values if hasattr(X_tr, "values") else X_tr, y_tr)
    return model


def run_model_cv(model_name, train_fn, X, y, X_test, X_orig, y_orig,
                 feature_cols, interaction_cols, n_folds, n_estimators,
                 early_stop, output_dir, sub_dir, test_ids, le):
    """Run full CV for one model, save predictions and submission.

    Args:
        model_name: Short name for files.
        train_fn: Callable(X_tr, y_tr, X_va, y_va) -> fitted model.
        X: Full training DataFrame.
        y: Full training target array.
        X_test: Full test DataFrame.
        X_orig: Original data DataFrame for injection.
        y_orig: Original data target array.
        feature_cols: List of feature column names.
        interaction_cols: 2-way interaction columns for in-fold TE.
        n_folds: Number of CV folds.
        n_estimators: Max estimators for GBDT models.
        early_stop: Early stopping rounds.
        output_dir: Path for .npy files.
        sub_dir: Path for submission CSVs.
        test_ids: Test set IDs for submission.
        le: Fitted LabelEncoder.

    Returns:
        Tuple of (oof_preds, test_preds, cv_score).
    """
    kfold = StratifiedKFold(n_splits=n_folds, shuffle=True, random_state=SEED)
    oof_preds = np.zeros((len(X), 3))
    test_preds = np.zeros((len(X_test), 3))
    fold_scores = []

    print(f"\n{'=' * 50}")
    print(f"  Training {model_name} ({n_folds}-fold CV)")
    print(f"{'=' * 50}")

    for fold, (train_idx, val_idx) in enumerate(kfold.split(X, y)):
        X_tr = X.iloc[train_idx][feature_cols].copy()
        y_tr = y[train_idx].copy()
        X_va = X.iloc[val_idx][feature_cols].copy()
        X_te = X_test[feature_cols].copy()

        # Inject original data into training fold
        X_orig_fold = X_orig[feature_cols].copy()
        X_tr = pd.concat([X_tr, X_orig_fold], axis=0).reset_index(drop=True)
        y_tr = np.concatenate([y_tr, y_orig])

        # In-fold target encoding and supervised binning
        X_tr, X_va, X_te = apply_fold_features(X_tr, X_va, X_te, y_tr)

        # Get final feature list after fold features
        fold_features = [c for c in X_tr.columns if c not in (set(CAT_COLS) | {"id", TARGET})]

        # Train
        model = train_fn(X_tr[fold_features], y_tr, X_va[fold_features], y[val_idx])

        # Predict
        if hasattr(model, "predict_proba"):
            oof_preds[val_idx] = model.predict_proba(X_va[fold_features])
            test_preds += model.predict_proba(X_te[fold_features]) / n_folds
        else:
            # pytabkit models
            va_vals = X_va[fold_features].values if hasattr(X_va, "values") else X_va[fold_features]
            te_vals = X_te[fold_features].values if hasattr(X_te, "values") else X_te[fold_features]
            oof_preds[val_idx] = model.predict_proba(va_vals)
            test_preds += model.predict_proba(te_vals) / n_folds

        score = balanced_accuracy_score(y[val_idx], oof_preds[val_idx].argmax(axis=1))
        fold_scores.append(score)
        print(f"  Fold {fold + 1}/{n_folds}: {score:.5f}")

        del model
        gc.collect()

    cv_score = balanced_accuracy_score(y, oof_preds.argmax(axis=1))
    print(f"  {model_name} CV: {cv_score:.5f} (+/- {np.std(fold_scores):.5f})")

    # Save predictions
    suffix = "_sc2"
    np.save(output_dir / f"oof_{model_name}{suffix}.npy", oof_preds)
    np.save(output_dir / f"pred_{model_name}{suffix}.npy", test_preds)

    # Save individual submission
    test_labels = le.inverse_transform(test_preds.argmax(axis=1))
    sub = pd.DataFrame({"id": test_ids, TARGET: test_labels})
    sub_path = sub_dir / f"sub_{model_name}{suffix}.csv"
    sub.to_csv(sub_path, index=False)
    print(f"  Saved: {sub_path}")

    return oof_preds, test_preds, cv_score


