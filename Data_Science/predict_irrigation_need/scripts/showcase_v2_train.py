def add_magic_features(df):
    """Add magic formula features from the original dataset rule.

    The original 10K dataset was generated by a deterministic formula
    involving threshold comparisons. These features expose that structure
    to the model.

    Args:
        df: DataFrame with raw feature columns.

    Returns:
        DataFrame with magic features appended.
    """
    df = df.copy()
    df["magic_soil_dry"] = (df["Soil_Moisture"] < 25).astype(np.int8)
    df["magic_rain_low"] = (df["Rainfall_mm"] < 300).astype(np.int8)
    df["magic_temp_hot"] = (df["Temperature_C"] > 30).astype(np.int8)
    df["magic_wind_high"] = (df["Wind_Speed_kmh"] > 10).astype(np.int8)
    df["magic_harvest"] = (df["Crop_Growth_Stage"] == "Harvest").astype(np.int8)
    df["magic_sowing"] = (df["Crop_Growth_Stage"] == "Sowing").astype(np.int8)
    df["magic_mulch_yes"] = (df["Mulching_Used"] == "Yes").astype(np.int8)

    df["magic_high_score"] = (
        df["magic_soil_dry"] * 2 + df["magic_rain_low"] * 2
        + df["magic_temp_hot"] + df["magic_wind_high"]
    )
    df["magic_low_score"] = (
        df["magic_harvest"] * 2 + df["magic_sowing"] * 2 + df["magic_mulch_yes"]
    )
    df["magic_score"] = df["magic_high_score"] - df["magic_low_score"]

    df["magic_soil_margin"] = 25 - df["Soil_Moisture"]
    df["magic_rain_margin"] = 300 - df["Rainfall_mm"]
    df["magic_temp_margin"] = df["Temperature_C"] - 30
    df["magic_wind_margin"] = df["Wind_Speed_kmh"] - 10
    df["magic_boundary_dist"] = df[
        ["magic_soil_margin", "magic_rain_margin",
         "magic_temp_margin", "magic_wind_margin"]
    ].abs().min(axis=1)
    return df


def add_domain_features(df):
    """Add domain-knowledge interaction features.

    Physics-inspired features for water balance, heat stress,
    evapotranspiration, and soil efficiency.

    Args:
        df: DataFrame with raw feature columns.

    Returns:
        DataFrame with domain features appended.
    """
    df = df.copy()
    df["water_balance"] = df["Rainfall_mm"] - df["Previous_Irrigation_mm"]
    df["heat_stress"] = df["Temperature_C"] * (100 - df["Humidity"]) / 100
    df["ET_proxy"] = (
        df["Temperature_C"] * df["Wind_Speed_kmh"]
        * (100 - df["Humidity"]) / 100
    )
    df["drying_index"] = (
        df["Wind_Speed_kmh"] * df["Temperature_C"]
        / df["Humidity"].clip(lower=1)
    )
    df["moisture_deficit"] = df["Soil_Moisture"] - df["Rainfall_mm"] / 10
    df["water_per_hectare"] = (
        (df["Rainfall_mm"] + df["Previous_Irrigation_mm"])
        / (df["Field_Area_hectare"] + 0.01)
    )
    df["moisture_temp_ratio"] = df["Soil_Moisture"] / (df["Temperature_C"] + 1)
    return df


def label_encode_categoricals(train, test, orig):
    """Label-encode categorical columns fitted on combined data.

    Args:
        train: Training DataFrame.
        test: Test DataFrame.
        orig: Original 10K DataFrame.

    Returns:
        Tuple of (train, test, orig) with _le columns added.
    """
    combined = pd.concat(
        [train[CAT_COLS], test[CAT_COLS], orig[CAT_COLS]], ignore_index=True,
    )
    for col in CAT_COLS:
        le = LabelEncoder()
        le.fit(combined[col].astype(str))
        for df in [train, test, orig]:
            df[f"{col}_le"] = le.transform(df[col].astype(str))
    return train, test, orig


def apply_feature_engine_static(train, test):
    """Apply feature-engine transformers that do not use the target.

    Fit on train, transform both train and test.

    Uses:
        CountFrequencyEncoder: category frequency as numeric.
        EqualFrequencyDiscretiser: quantile binning (10 bins).
        EqualWidthDiscretiser: fixed-width binning (15 bins).
        RelativeFeatures: pairwise ratios and products.
        MathFeatures: aggregate statistics of feature groups.

    Args:
        train: Training DataFrame.
        test: Test DataFrame.

    Returns:
        Tuple of (train, test, list of new column names).
    """
    new_cols = []

    # 1. Frequency encoding for categoricals
    cfe = CountFrequencyEncoder(
        encoding_method="frequency", variables=CAT_COLS, missing_values="ignore",
    )
    cfe.fit(train[CAT_COLS])
    cfe_train = cfe.transform(train[CAT_COLS].copy())
    cfe_test = cfe.transform(test[CAT_COLS].copy())
    for col in CAT_COLS:
        name = f"cfe_{col}"
        train[name] = cfe_train[col].values
        test[name] = cfe_test[col].values
        new_cols.append(name)

    # 2. Equal-frequency binning (quantile, 10 bins)
    efd = EqualFrequencyDiscretiser(q=10, variables=BIN_COLS, return_boundaries=False)
    efd.fit(train[BIN_COLS])
    efd_train = efd.transform(train[BIN_COLS].copy())
    efd_test = efd.transform(test[BIN_COLS].copy())
    for col in BIN_COLS:
        name = f"efd10_{col}"
        train[name] = efd_train[col].values
        test[name] = efd_test[col].values
        new_cols.append(name)

    # 3. Equal-width binning (15 bins)
    ewd = EqualWidthDiscretiser(bins=15, variables=BIN_COLS, return_boundaries=False)
    ewd.fit(train[BIN_COLS])
    ewd_train = ewd.transform(train[BIN_COLS].copy())
    ewd_test = ewd.transform(test[BIN_COLS].copy())
    for col in BIN_COLS:
        name = f"ewd15_{col}"
        train[name] = ewd_train[col].values
        test[name] = ewd_test[col].values
        new_cols.append(name)

    # 4. Relative features: pairwise differences and products
    rel_vars = ["Soil_Moisture", "Temperature_C", "Humidity"]
    rel_refs = ["Wind_Speed_kmh", "Rainfall_mm"]
    rel_input_cols = rel_vars + rel_refs
    rel_tf = RelativeFeatures(
        variables=rel_vars, reference=rel_refs, func=["sub", "mul"],
    )
    rel_tf.fit(train[rel_input_cols])
    rel_train = rel_tf.transform(train[rel_input_cols].copy())
    rel_test = rel_tf.transform(test[rel_input_cols].copy())
    rel_new = [c for c in rel_train.columns if c not in rel_input_cols]
    for col in rel_new:
        train[col] = rel_train[col].values
        test[col] = rel_test[col].values
    new_cols.extend(rel_new)

    # 5. Aggregate math features: mean and std of top features
    math_vars = ["Soil_Moisture", "Temperature_C", "Humidity", "Wind_Speed_kmh"]
    math_tf = MathFeatures(variables=math_vars, func=["mean", "std"], missing_values="ignore")
    math_tf.fit(train[math_vars])
    math_train = math_tf.transform(train[math_vars].copy())
    math_test = math_tf.transform(test[math_vars].copy())
    math_new = [c for c in math_train.columns if c not in math_vars]
    for col in math_new:
        train[col] = math_train[col].values
        test[col] = math_test[col].values
    new_cols.extend(math_new)

    return train, test, new_cols


def add_original_te_priors(train, test, orig):
    """Add target encoding priors from the original 10K dataset.

    For each categorical column, compute mean target per category from
    the original data. Leakage-free because the original dataset is
    independent of the synthetic split.

    Args:
        train: Training DataFrame.
        test: Test DataFrame.
        orig: Original DataFrame with TARGET column.

    Returns:
        Tuple of (train, test, list of new column names).
    """
    le = LabelEncoder()
    le.fit(LABEL_ORDER)
    orig_y = le.transform(orig[TARGET])
    global_mean = orig_y.mean()

    prior_cols = []
    for col in CAT_COLS:
        name = f"orig_prior_{col}"
        te_map = pd.Series(orig_y).groupby(orig[col]).mean()
        train[name] = train[col].map(te_map).fillna(global_mean).astype(np.float32)
        test[name] = test[col].map(te_map).fillna(global_mean).astype(np.float32)
        prior_cols.append(name)

    return train, test, prior_cols


def create_2way_interactions(train, test):
    """Create 2-way categorical interaction columns as factorized integers.

    Generates all C(19,2) = 171 pairs from numeric + categorical columns.
    Drops high-cardinality pairs where more than 50% of values are unique.

    Args:
        train: Training DataFrame.
        test: Test DataFrame.

    Returns:
        Tuple of (train, test, list of interaction column names).
    """
    all_cols = NUMERIC_COLS + CAT_COLS
    interaction_cols = []

    for col_a, col_b in combinations(all_cols, 2):
        name = f"{col_a}-{col_b}"
        combined = pd.concat([
            train[col_a].astype(str) + "_" + train[col_b].astype(str),
            test[col_a].astype(str) + "_" + test[col_b].astype(str),
        ], ignore_index=True)
        encoded, _ = combined.factorize()
        if pd.Series(encoded).nunique() > len(combined) // 2:
            continue
        train[name] = encoded[:len(train)]
        test[name] = encoded[len(train):]
        interaction_cols.append(name)

    return train, test, interaction_cols


def apply_fold_features(X_train, X_val, X_test, y_train):
    """Apply target-dependent feature-engine transformers inside a CV fold.

    DecisionTreeDiscretiser: supervised binning using a shallow decision tree.
    MeanEncoder: target encoding for bigram interaction columns.

    Fit on training fold only, transform val and test.

    Args:
        X_train: Training fold features.
        X_val: Validation fold features.
        X_test: Test features.
        y_train: Training fold target (numeric).

    Returns:
        Tuple of (X_train, X_val, X_test) with fold features added.
    """
    y_series = pd.Series(y_train, index=X_train.index)

    # 1. Decision tree supervised binning
    bin_cols_present = [c for c in BIN_COLS if c in X_train.columns]
    dtd = DecisionTreeDiscretiser(
        variables=bin_cols_present,
        regression=False,
        scoring="balanced_accuracy",
        cv=3,
        param_grid={"max_depth": [2, 3]},
    )
    dtd.fit(X_train[bin_cols_present], y_series)
    dtd_train = dtd.transform(X_train[bin_cols_present].copy())
    dtd_val = dtd.transform(X_val[bin_cols_present].copy())
    dtd_test = dtd.transform(X_test[bin_cols_present].copy())
    for col in bin_cols_present:
        name = f"dtd_{col}"
        X_train[name] = dtd_train[col].values
        X_val[name] = dtd_val[col].values
        X_test[name] = dtd_test[col].values

    # 2. Mean target encoding for interaction pairs
    # Use label-encoded versions since original categoricals may not be present
    interaction_present = []
    for c1, c2 in INTERACTION_PAIRS:
        le_c1 = f"{c1}_le" if f"{c1}_le" in X_train.columns else c1
        le_c2 = f"{c2}_le" if f"{c2}_le" in X_train.columns else c2
        name = f"bigram_{c1}_{c2}"
        for df in [X_train, X_val, X_test]:
            df[name] = df[le_c1].astype(str) + "_" + df[le_c2].astype(str)
        interaction_present.append(name)

    global_mean = y_train.mean()
    for col in interaction_present:
        te_map = y_series.groupby(X_train[col]).mean()
        X_train[f"{col}_te"] = X_train[col].map(te_map).fillna(global_mean)
        X_val[f"{col}_te"] = X_val[col].map(te_map).fillna(global_mean)
        X_test[f"{col}_te"] = X_test[col].map(te_map).fillna(global_mean)

    # Drop the raw string bigram columns
    for col in interaction_present:
        X_train.drop(columns=[col], inplace=True)
        X_val.drop(columns=[col], inplace=True)
        X_test.drop(columns=[col], inplace=True)

    return X_train, X_val, X_test


def build_all_static_features(train, test, orig):
    """Full static feature engineering pipeline.

    Args:
        train: Training DataFrame.
        test: Test DataFrame.
        orig: Original 10K DataFrame.

    Returns:
        Tuple of (train, test, orig, feature_cols, interaction_cols).
    """
    print("Feature engineering: magic formula...")
    train = add_magic_features(train)
    test = add_magic_features(test)
    orig = add_magic_features(orig)

    print("Feature engineering: domain features...")
    train = add_domain_features(train)
    test = add_domain_features(test)
    orig = add_domain_features(orig)

    print("Feature engineering: label encoding...")
    train, test, orig = label_encode_categoricals(train, test, orig)

    print("Feature engineering: feature-engine (static)...")
    train, test, fe_cols = apply_feature_engine_static(train, test)
    print(f"  Feature-engine added {len(fe_cols)} columns")

    print("Feature engineering: original TE priors...")
    train, test, prior_cols = add_original_te_priors(train, test, orig)
    print(f"  Original priors: {len(prior_cols)} columns")

    print("Feature engineering: 2-way interactions...")
    train, test, interaction_cols = create_2way_interactions(train, test)
    print(f"  Interaction columns: {len(interaction_cols)}")

    # Also apply static features to orig for injection
    # Fill missing columns with 0
    for col in train.columns:
        if col not in orig.columns:
            orig[col] = 0

    exclude = {"id", TARGET} | set(CAT_COLS)
    feature_cols = [c for c in train.columns if c not in exclude]
    print(f"Total features: {len(feature_cols)}")

    return train, test, orig, feature_cols, interaction_cols


